def hole(x0, y0, mask, kind, cols):
    """mask：手打的形狀（# = 破口）；kind 'brick' / 'lath'；cols：這個破口裡逐塊磚的顏色"""
    H_ = len(mask); pts = {(x0 + i, y0 + j) for j, r in enumerate(mask) for i, ch in enumerate(r) if ch == '#'}
    for (x, y) in sorted(pts):
        edge = any((x + dx, y + dy) not in pts for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))
        top = (x, y - 1) not in pts
        if edge: c.px(x, y, 'D2' if top else 'P0'); continue
        if (x, y - 1) in pts and ((x, y - 2) not in pts): c.px(x, y, 'R1' if kind == 'brick' else 'D1'); continue      # 灰泥厚度的影子
        if kind == 'brick':
            r = (y - 101) // 4; ry = (y - 101) % 4; off = (0 if r % 2 == 0 else 6); bx = (x - off) % 12; bi = (x - off) // 12
            k = cols[(bi + r * 2) % len(cols)]
            c.px(x, y, 'M0' if (ry == 3 or bx == 11) else (BR[max(k - 1, 0)] if ry == 2 else BR[k]))
        else:
            ry = (y - y0) % 3
            c.px(x, y, 'D1' if ry == 2 else ('D4' if (ry == 0 and (x * 7 + y) % 11 != 0) else 'D3'))
