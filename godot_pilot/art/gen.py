def gen(spec):
    name = spec.split(':')[0]
    n = len(glob.glob(os.path.join(RAW, name + '_v*.png'))) + len([l for l in open(os.path.join(RAW, 'gen_log.txt')).read().splitlines() if l.startswith('FAIL ' + name + ' ')] if os.path.exists(os.path.join(RAW, 'gen_log.txt')) else [])
    d = os.path.join(WORK, f'gen_{name}_{n+1}_{os.getpid()}_{int(time.time()*1000)%100000}'); shutil.rmtree(d, ignore_errors=True); os.makedirs(d)
    extra = sys_extra.get(name, '')
    p = f"請用你的圖片生成功能產生一張圖片。{RULES}\n{P[name]}{extra}\n完成後把圖片存成目前目錄下的 ./{name}.png（只要這一個檔案，不要做其他事）。"
    open(os.path.join(d, 'prompt.txt'), 'w').write(p)
    imgs = [TARGET] + ([os.path.join(WORK, 'ref_%s.png' % name)] if os.path.exists(os.path.join(WORK, 'ref_%s.png' % name)) else [])
    t0 = time.time()
    try:
        r = subprocess.run(['codex', 'exec', '-s', 'workspace-write', '--skip-git-repo-check', '-C', d, '-i'] + imgs, input=p.encode(), stdout=open(os.path.join(d, 'out.log'), 'wb'), stderr=subprocess.STDOUT, timeout=540)
        rc = r.returncode
    except subprocess.TimeoutExpired:
        rc = 'timeout'
    dt = time.time() - t0
    out = os.path.join(d, name + '.png'); ok = os.path.exists(out)
    k = len(glob.glob(os.path.join(RAW, name + '_v*.png'))) + 1
    if ok: shutil.copy(out, os.path.join(RAW, f'{name}_v{k}.png'))
    line = f"{'ok  ' if ok else 'FAIL'} {name} {'v%d' % k if ok else ''} rc={rc} {dt:.0f}s" + (' QUOTA?' if (not ok and dt < 15) else '')
    open(os.path.join(RAW, 'gen_log.txt'), 'a').write(line + '\n'); print(line, flush=True)
sys_extra = {}
names = []
for a in sys.argv[1:]:
    if a.startswith('+'): sys_extra[names[-1]] = a[1:]
    else: names.append(a)
with ThreadPoolExecutor(4) as ex: list(ex.map(gen, names))
